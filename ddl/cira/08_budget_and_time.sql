-- 1. SN_CIRA_PROJECT_BUDGET (프로젝트 예산)

-- ----------------------------------------------------------
CREATE TABLE SN_CIRA_PROJECT_BUDGET
(
    OBJ_ID          VARCHAR(100)   NOT NULL,
    PROJECT_ID      VARCHAR(100)   NOT NULL,
    TOTAL_BUDGET    NUMERIC(15, 2) NOT NULL,
    BUDGET_CATEGORY VARCHAR(50)    NOT NULL DEFAULT 'TOTAL', -- TOTAL | DEVELOPMENT | DESIGN | QA | OTHER
    CURRENCY        VARCHAR(3)     NOT NULL DEFAULT 'KRW',
    FISCAL_YEAR     SMALLINT,
    -- BaseModel
    SRV_ID          VARCHAR(50)    NOT NULL DEFAULT 'CIRA',
    TENANT          VARCHAR(50)    NOT NULL DEFAULT 'TAS',
    TRACE_ID        VARCHAR(100)   NOT NULL,
    USE_STAT_CD     VARCHAR(40)    NOT NULL DEFAULT 'Usable',
    EVNT_NM         VARCHAR(100)   NOT NULL,
    PREV_EVNT_NM    VARCHAR(100),
    ACT_CD          VARCHAR(100),
    ACT_CM          TEXT,
    CREATED_BY      VARCHAR(40),
    CREATED_AT      TIMESTAMP      NOT NULL DEFAULT NOW(),
    MODIFIED_BY     VARCHAR(40),
    MODIFIED_AT     TIMESTAMP      NOT NULL DEFAULT NOW(),

    CONSTRAINT PK_SN_CIRA_PROJECT_BUDGET PRIMARY KEY (OBJ_ID),
    CONSTRAINT FK_SN_CIRA_PROJECT_BUDGET_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES SN_CIRA_PROJECT (OBJ_ID)
);


CREATE INDEX IDX_SN_CIRA_PROJECT_BUDGET_PROJECT_ID ON SN_CIRA_PROJECT_BUDGET (PROJECT_ID);

