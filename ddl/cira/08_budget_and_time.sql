COMMENT
ON COLUMN SN_CIRA_PROJECT_BUDGET.TOTAL_BUDGET IS '총 예산';
COMMENT
ON COLUMN SN_CIRA_PROJECT_BUDGET.BUDGET_CATEGORY IS '예산 카테고리 (TOTAL | DEVELOPMENT | DESIGN | QA | OTHER)';
COMMENT
ON COLUMN SN_CIRA_PROJECT_BUDGET.CURRENCY IS '통화 코드 (KRW | USD …)';
COMMENT
ON COLUMN SN_CIRA_PROJECT_BUDGET.FISCAL_YEAR IS '회계 연도';
COMMENT
ON COLUMN SN_CIRA_PROJECT_BUDGET.OBJ_ID IS '오브젝트 ID (PK, UUID)';
COMMENT
ON COLUMN SN_CIRA_PROJECT_BUDGET.SRV_ID IS '서비스명';
COMMENT
ON COLUMN SN_CIRA_PROJECT_BUDGET.TENANT IS '테넌트';
COMMENT
ON COLUMN SN_CIRA_PROJECT_BUDGET.TRACE_ID IS '트레이스 ID';
COMMENT
