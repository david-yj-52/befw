-- ----------------------------------------------------------
-- 3. SN_CIRA_GIT_PR (Git Pull Request 정보)

-- ----------------------------------------------------------
CREATE TABLE SN_CIRA_GIT_PR
(
    OBJ_ID       VARCHAR(100) NOT NULL,
    REPO_ID      VARCHAR(100) NOT NULL,
    ISSUE_ID     VARCHAR(100),
    PR_NO        INTEGER      NOT NULL,
    TITLE        VARCHAR(500) NOT NULL,
    DESCR        TEXT,
    PR_STAT      VARCHAR(20)  NOT NULL DEFAULT 'OPEN', -- OPEN | MERGED | CLOSED | DRAFT
    SRC_BRANCH   VARCHAR(200),
    TGT_BRANCH   VARCHAR(200),
    AUTHOR_NM    VARCHAR(100),
    AUTHOR_EMAIL VARCHAR(255),
    MERGED_AT    TIMESTAMP,
    CLOSED_AT    TIMESTAMP,
    -- BaseModel
    SRV_ID       VARCHAR(50)  NOT NULL DEFAULT 'CIRA',
    TENANT       VARCHAR(50)  NOT NULL DEFAULT 'TAS',
    TRACE_ID     VARCHAR(100) NOT NULL,
    USE_STAT_CD  VARCHAR(40)  NOT NULL DEFAULT 'Usable',
    EVNT_NM      VARCHAR(100) NOT NULL,
    PREV_EVNT_NM VARCHAR(100),
    ACT_CD       VARCHAR(100),
    ACT_CM       TEXT,
    CREATED_BY   VARCHAR(40),
    CREATED_AT   TIMESTAMP    NOT NULL DEFAULT NOW(),
    MODIFIED_BY  VARCHAR(40),
    MODIFIED_AT  TIMESTAMP    NOT NULL DEFAULT NOW(),

    CONSTRAINT PK_SN_CIRA_GIT_PR PRIMARY KEY (OBJ_ID),
    CONSTRAINT UK_SN_CIRA_GIT_PR UNIQUE (REPO_ID, PR_NO),
    CONSTRAINT FK_SN_CIRA_GIT_PR_REPO FOREIGN KEY (REPO_ID) REFERENCES SN_CIRA_GIT_REPO (OBJ_ID),
    CONSTRAINT FK_SN_CIRA_GIT_PR_ISSUE FOREIGN KEY (ISSUE_ID) REFERENCES SN_CIRA_ISSUE (OBJ_ID)
);


CREATE INDEX IDX_SN_CIRA_GIT_PR_REPO_ID ON SN_CIRA_GIT_PR (REPO_ID);
CREATE INDEX IDX_SN_CIRA_GIT_PR_ISSUE_ID ON SN_CIRA_GIT_PR (ISSUE_ID) WHERE ISSUE_ID IS NOT NULL;
CREATE INDEX IDX_SN_CIRA_GIT_PR_STAT ON SN_CIRA_GIT_PR (REPO_ID, PR_STAT);

