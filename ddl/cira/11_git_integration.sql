COMMENT
ON COLUMN SN_CIRA_GIT_COMMIT.COMMIT_HASH IS '커밋 해시 (40자)';
COMMENT
ON COLUMN SN_CIRA_GIT_COMMIT.MSG IS '커밋 메시지';
COMMENT
ON COLUMN SN_CIRA_GIT_COMMIT.AUTHOR_NM IS '커밋 작성자명';
COMMENT
ON COLUMN SN_CIRA_GIT_COMMIT.AUTHOR_EMAIL IS '커밋 작성자 이메일';
COMMENT
ON COLUMN SN_CIRA_GIT_COMMIT.COMMIT_DT IS '커밋 일시';
COMMENT
ON COLUMN SN_CIRA_GIT_COMMIT.OBJ_ID IS '오브젝트 ID (PK, UUID)';
COMMENT
ON COLUMN SN_CIRA_GIT_COMMIT.SRV_ID IS '서비스명';
COMMENT
ON COLUMN SN_CIRA_GIT_COMMIT.TENANT IS '테넌트';
