-- ----------------------------------------------------------
-- 3. FTS 자동 갱신 트리거

-- ----------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_sync_issue_search_vec()
    RETURNS TRIGGER AS
$$
BEGIN
    INSERT INTO SN_CIRA_ISSUE_SEARCH_IDX
    (OBJ_ID, ISSUE_ID, SEARCH_VEC, SRV_ID, TENANT, TRACE_ID, USE_STAT_CD, EVNT_NM, CREATED_BY, CREATED_AT, MODIFIED_BY,
     MODIFIED_AT)
    VALUES (gen_random_uuid()::TEXT,
            NEW.OBJ_ID,
            TO_TSVECTOR('simple',
                        COALESCE(NEW.ISSUE_KEY, '') || ' ' ||
                        COALESCE(NEW.TITLE, '') || ' ' ||
                        COALESCE(NEW.CONTENT, '')
            ),
            NEW.SRV_ID, NEW.TENANT, NEW.TRACE_ID, 'Usable', 'SyncSearchVec',
            NEW.CREATED_BY, NOW(), NEW.MODIFIED_BY, NOW())
    ON CONFLICT (ISSUE_ID) DO UPDATE
        SET SEARCH_VEC  = EXCLUDED.SEARCH_VEC,
            MODIFIED_AT = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER TRG_SN_CIRA_ISSUE_SEARCH_SYNC
    AFTER INSERT OR UPDATE OF TITLE, CONTENT
    ON SN_CIRA_ISSUE
    FOR EACH ROW
EXECUTE FUNCTION fn_sync_issue_search_vec();
