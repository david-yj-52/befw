-- 1. SN_CIRA_SAVED_FILTER (저장된 검색 필터)

-- ----------------------------------------------------------
CREATE TABLE SN_CIRA_SAVED_FILTER
(
    OBJ_ID          VARCHAR(100) NOT NULL,
    USER_ID         VARCHAR(100) NOT NULL,
    PROJECT_ID      VARCHAR(100), -- NULL = 전역 필터
    FILTER_NM       VARCHAR(200) NOT NULL,
    JQL_QUERY       TEXT         NOT NULL,
    SHARED_YN       VARCHAR(1)   NOT NULL DEFAULT 'N',
    -- BaseModel
    SRV_ID          VARCHAR(50)  NOT NULL DEFAULT 'CIRA',
    TENANT          VARCHAR(50)  NOT NULL DEFAULT 'TAS',
    TRACE_ID        VARCHAR(100) NOT NULL,
    USE_STAT_CD     VARCHAR(40)  NOT NULL DEFAULT 'Usable',
    EVNT_NM         VARCHAR(100) NOT NULL,
    PREV_EVNT_NM     VARCHAR(100),
    ACT_CD       VARCHAR(100),
    ACT_CM          TEXT,
    CREATED_BY      VARCHAR(40),
    CREATED_AT      TIMESTAMP    NOT NULL DEFAULT NOW(),
    MODIFIED_BY     VARCHAR(40),
    MODIFIED_AT     TIMESTAMP    NOT NULL DEFAULT NOW(),

    CONSTRAINT PK_SN_CIRA_SAVED_FILTER PRIMARY KEY (OBJ_ID),
    CONSTRAINT FK_SN_CIRA_SAVED_FILTER_USER FOREIGN KEY (USER_ID) REFERENCES GS_USER (OBJ_ID),
    CONSTRAINT FK_SN_CIRA_SAVED_FILTER_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES SN_CIRA_PROJECT (OBJ_ID)
);


CREATE INDEX IDX_SN_CIRA_SAVED_FILTER_USER_ID ON SN_CIRA_SAVED_FILTER (USER_ID);
CREATE INDEX IDX_SN_CIRA_SAVED_FILTER_PROJECT_ID ON SN_CIRA_SAVED_FILTER (PROJECT_ID) WHERE PROJECT_ID IS NOT NULL;

COMMENT ON TABLE SN_CIRA_SAVED_FILTER IS '저장된 검색 필터';
COMMENT ON COLUMN SN_CIRA_SAVED_FILTER.USER_ID IS '소유자 ID (FK → GS_USER)';
COMMENT ON COLUMN SN_CIRA_SAVED_FILTER.PROJECT_ID IS '프로젝트 ID (NULL=전역, FK → SN_CIRA_PROJECT)';
COMMENT ON COLUMN SN_CIRA_SAVED_FILTER.FILTER_NM IS '필터명';
COMMENT ON COLUMN SN_CIRA_SAVED_FILTER.JQL_QUERY IS 'JQL 쿼리 문자열';
COMMENT ON COLUMN SN_CIRA_SAVED_FILTER.SHARED_YN IS '공유 여부 (Y | N)';
COMMENT ON COLUMN SN_CIRA_SAVED_FILTER.OBJ_ID IS '오브젝트 ID (PK, UUID)';
COMMENT ON COLUMN SN_CIRA_SAVED_FILTER.SRV_ID IS '서비스명';
COMMENT ON COLUMN SN_CIRA_SAVED_FILTER.TENANT IS '테넌트';
