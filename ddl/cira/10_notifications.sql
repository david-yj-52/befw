-- ----------------------------------------------------------
-- 3. SN_CIRA_AUDIT_LOG (감사 로그 (월별 파티셔닝))

-- ----------------------------------------------------------
CREATE TABLE SN_CIRA_AUDIT_LOG
(
    OBJ_ID          VARCHAR(100) NOT NULL,
    ACTION_TYPE     VARCHAR(30)  NOT NULL, -- CREATE | UPDATE | DELETE | LOGIN | LOGOUT
    ACTOR_ID        VARCHAR(100),
    RESOURCE_TYPE   VARCHAR(50)  NOT NULL, -- ISSUE | PROJECT | USER | ROLE …
    RESOURCE_ID     VARCHAR(100) NOT NULL,
    OLD_SNAPSHOT    JSONB,
    NEW_SNAPSHOT    JSONB,
    IP_ADDR         VARCHAR(45),
    USER_AGENT      TEXT,
    -- BaseModel
    SRV_ID          VARCHAR(50)  NOT NULL DEFAULT 'CIRA',
    TENANT          VARCHAR(50)  NOT NULL DEFAULT 'TAS',
    TRACE_ID        VARCHAR(100) NOT NULL,
    USE_STAT_CD     VARCHAR(40)  NOT NULL DEFAULT 'Usable',
    EVNT_NM         VARCHAR(100) NOT NULL,
    PREV_EVNT_NM     VARCHAR(100),
    ACT_CD       VARCHAR(100),
    ACT_CM          TEXT,
    CREATED_BY      VARCHAR(40),
    CREATED_AT      TIMESTAMP    NOT NULL DEFAULT NOW(),
    MODIFIED_BY     VARCHAR(40),
    MODIFIED_AT     TIMESTAMP    NOT NULL DEFAULT NOW(),

    CONSTRAINT PK_SN_CIRA_AUDIT_LOG PRIMARY KEY (OBJ_ID, CREATED_AT)
) PARTITION BY RANGE (CREATED_AT);

-- 파티션 예시 (월별 분리)
CREATE TABLE SN_CIRA_AUDIT_LOG_2026_05 PARTITION OF SN_CIRA_AUDIT_LOG
    FOR VALUES FROM ('2026-05-01') TO ('2026-06-01');
CREATE TABLE SN_CIRA_AUDIT_LOG_2026_06 PARTITION OF SN_CIRA_AUDIT_LOG
    FOR VALUES FROM ('2026-06-01') TO ('2026-07-01');


CREATE INDEX IDX_SN_CIRA_AUDIT_LOG_ACTOR ON SN_CIRA_AUDIT_LOG (ACTOR_ID);
CREATE INDEX IDX_SN_CIRA_AUDIT_LOG_RESOURCE ON SN_CIRA_AUDIT_LOG (RESOURCE_TYPE, RESOURCE_ID);
CREATE INDEX IDX_SN_CIRA_AUDIT_LOG_CREATED ON SN_CIRA_AUDIT_LOG (CREATED_AT DESC);

COMMENT ON TABLE SN_CIRA_AUDIT_LOG IS '감사 로그 (월별 파티셔닝)';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.ACTION_TYPE IS '액션 유형 (CREATE | UPDATE | DELETE | LOGIN | LOGOUT)';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.ACTOR_ID IS '행위자 ID (FK → GS_USER)';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.RESOURCE_TYPE IS '리소스 유형 (ISSUE | PROJECT | USER …)';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.RESOURCE_ID IS '리소스 ID';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.OLD_SNAPSHOT IS '변경 전 데이터 스냅샷 (JSONB)';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.NEW_SNAPSHOT IS '변경 후 데이터 스냅샷 (JSONB)';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.IP_ADDR IS '요청 IP 주소';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.USER_AGENT IS '요청 User-Agent';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.OBJ_ID IS '오브젝트 ID (PK, UUID)';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.SRV_ID IS '서비스명';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.TENANT IS '테넌트';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.TRACE_ID IS '트레이스 ID';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.USE_STAT_CD IS '사용 상태';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.EVNT_NM IS '이벤트명';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.PREV_EVNT_NM IS '이전 이벤트명';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.ACT_CD IS '액션 사유 코드';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.ACT_CM IS '액션 코멘트';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.CREATED_BY IS '생성자';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.CREATED_AT IS '생성일시';
COMMENT ON COLUMN SN_CIRA_AUDIT_LOG.MODIFIED_BY IS '수정자';
