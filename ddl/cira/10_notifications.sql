-- ----------------------------------------------------------
-- 1. SN_CIRA_NOTIFICATION (알림)

-- ----------------------------------------------------------
CREATE TABLE SN_CIRA_NOTIFICATION
(
    OBJ_ID          VARCHAR(100) NOT NULL,
    USER_ID         VARCHAR(100) NOT NULL,
    NOTIF_TYPE      VARCHAR(50)  NOT NULL, -- ISSUE_ASSIGNED | COMMENT_ADDED | STATUS_CHANGED | MENTIONED | SPRINT_STARTED …
    TITLE           VARCHAR(300) NOT NULL,
    MSG             TEXT,
    RESOURCE_TYPE   VARCHAR(50),           -- ISSUE | PROJECT | SPRINT | COMMENT
    RESOURCE_ID     VARCHAR(100),
    READ_YN         VARCHAR(1)   NOT NULL DEFAULT 'N',
    -- BaseModel
    SRV_ID          VARCHAR(50)  NOT NULL DEFAULT 'CIRA',
    TENANT          VARCHAR(50)  NOT NULL DEFAULT 'TAS',
    TRACE_ID        VARCHAR(100) NOT NULL,
    USE_STAT_CD     VARCHAR(40)  NOT NULL DEFAULT 'Usable',
    EVNT_NM         VARCHAR(100) NOT NULL,
    PREV_EVNT_NM     VARCHAR(100),
    ACT_CD       VARCHAR(100),
    ACT_CM          TEXT,
    CREATED_BY      VARCHAR(40),
    CREATED_AT      TIMESTAMP    NOT NULL DEFAULT NOW(),
    MODIFIED_BY     VARCHAR(40),
    MODIFIED_AT     TIMESTAMP    NOT NULL DEFAULT NOW(),

    CONSTRAINT PK_SN_CIRA_NOTIFICATION PRIMARY KEY (OBJ_ID),
    CONSTRAINT FK_SN_CIRA_NOTIFICATION_USER FOREIGN KEY (USER_ID) REFERENCES GS_USER (OBJ_ID)
);


CREATE INDEX IDX_SN_CIRA_NOTIFICATION_USER_ID ON SN_CIRA_NOTIFICATION (USER_ID, READ_YN, CREATED_AT DESC);
CREATE INDEX IDX_SN_CIRA_NOTIFICATION_CREATED ON SN_CIRA_NOTIFICATION (CREATED_AT DESC);

COMMENT ON TABLE SN_CIRA_NOTIFICATION IS '알림';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.USER_ID IS '수신자 ID (FK → GS_USER)';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.NOTIF_TYPE IS '알림 유형 (ISSUE_ASSIGNED | COMMENT_ADDED …)';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.TITLE IS '알림 제목';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.MSG IS '알림 내용';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.RESOURCE_TYPE IS '연관 리소스 유형 (ISSUE | PROJECT | SPRINT | COMMENT)';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.RESOURCE_ID IS '연관 리소스 ID';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.READ_YN IS '읽음 여부 (Y | N)';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.OBJ_ID IS '오브젝트 ID (PK, UUID)';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.SRV_ID IS '서비스명';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.TENANT IS '테넌트';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.TRACE_ID IS '트레이스 ID';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.USE_STAT_CD IS '사용 상태';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.EVNT_NM IS '이벤트명';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.PREV_EVNT_NM IS '이전 이벤트명';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.ACT_CD IS '액션 사유 코드';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.ACT_CM IS '액션 코멘트';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.CREATED_BY IS '생성자';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.CREATED_AT IS '생성일시';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.MODIFIED_BY IS '수정자';
COMMENT ON COLUMN SN_CIRA_NOTIFICATION.MODIFIED_AT IS '수정일시';

