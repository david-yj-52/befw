-- 1. GS_USER (사용자 기본 정보)

-- ----------------------------------------------------------
CREATE TABLE GS_USER
(
    OBJ_ID       VARCHAR(100) NOT NULL,
    EMAIL        VARCHAR(255) NOT NULL,
    USER_NM      VARCHAR(100) NOT NULL,
    AVATAR_URL   VARCHAR(500),
    PWD_HASH     VARCHAR(255) NOT NULL,
    -- BaseModel
    SRV_ID       VARCHAR(50)  NOT NULL DEFAULT 'CIRA',
    TENANT       VARCHAR(50)  NOT NULL DEFAULT 'TAS',
    TRACE_ID     VARCHAR(100) NOT NULL,
    USE_STAT_CD  VARCHAR(40)  NOT NULL DEFAULT 'Usable',
    EVNT_NM      VARCHAR(100) NOT NULL,
    PREV_EVNT_NM     VARCHAR(100),
    ACT_CD       VARCHAR(100),
    ACT_CM       TEXT,
    -- BasicAudit
    CREATED_BY   VARCHAR(40),
    CREATED_AT   TIMESTAMP    NOT NULL DEFAULT NOW(),
    MODIFIED_BY  VARCHAR(40),
    MODIFIED_AT  TIMESTAMP    NOT NULL DEFAULT NOW(),

    CONSTRAINT PK_GS_USER PRIMARY KEY (OBJ_ID),
    CONSTRAINT UK_GS_USER_EMAIL UNIQUE (EMAIL)
);


CREATE INDEX IDX_GS_USER_USE_STAT ON GS_USER (USE_STAT_CD);

COMMENT ON TABLE GS_USER IS '사용자 기본 정보';
COMMENT ON COLUMN GS_USER.EMAIL IS '이메일 (UK)';
COMMENT ON COLUMN GS_USER.USER_NM IS '사용자명';
COMMENT ON COLUMN GS_USER.AVATAR_URL IS '프로필 이미지 URL';
COMMENT ON COLUMN GS_USER.PWD_HASH IS '비밀번호 해시';
COMMENT ON COLUMN GS_USER.OBJ_ID IS '오브젝트 ID (PK, UUID)';
COMMENT ON COLUMN GS_USER.SRV_ID IS '서비스명';
COMMENT ON COLUMN GS_USER.TENANT IS '테넌트';
COMMENT ON COLUMN GS_USER.TRACE_ID IS '트레이스 ID';
COMMENT ON COLUMN GS_USER.USE_STAT_CD IS '사용 상태';
COMMENT ON COLUMN GS_USER.EVNT_NM IS '이벤트명';
COMMENT ON COLUMN GS_USER.PREV_EVNT_NM IS '이전 이벤트명';
COMMENT ON COLUMN GS_USER.ACT_CD IS '액션 사유 코드';
