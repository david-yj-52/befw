COMMENT ON COLUMN SN_CIRA_BOARD_COLUMN.COLUMN_NM IS '컬럼명';
COMMENT ON COLUMN SN_CIRA_BOARD_COLUMN.WIP_LIMIT IS 'WIP 제한 (NULL=제한 없음)';
COMMENT ON COLUMN SN_CIRA_BOARD_COLUMN.SORT_ORD IS '컬럼 정렬 순서';
COMMENT ON COLUMN SN_CIRA_BOARD_COLUMN.OBJ_ID IS '오브젝트 ID (PK, UUID)';
COMMENT ON COLUMN SN_CIRA_BOARD_COLUMN.SRV_ID IS '서비스명';
COMMENT ON COLUMN SN_CIRA_BOARD_COLUMN.TENANT IS '테넌트';
COMMENT ON COLUMN SN_CIRA_BOARD_COLUMN.TRACE_ID IS '트레이스 ID';
COMMENT ON COLUMN SN_CIRA_BOARD_COLUMN.USE_STAT_CD IS '사용 상태';
COMMENT ON COLUMN SN_CIRA_BOARD_COLUMN.EVNT_NM IS '이벤트명';
COMMENT ON COLUMN SN_CIRA_BOARD_COLUMN.PREV_EVNT_NM IS '이전 이벤트명';
COMMENT ON COLUMN SN_CIRA_BOARD_COLUMN.ACT_CD IS '액션 사유 코드';
