-- ----------------------------------------------------------
-- 3. SN_CIRA_ISSUE_POSITION (보드 내 이슈 위치 (Lexorank))

-- ----------------------------------------------------------
CREATE TABLE SN_CIRA_ISSUE_POSITION
(
    OBJ_ID          VARCHAR(100) NOT NULL,
    ISSUE_ID        VARCHAR(100) NOT NULL,
    COLUMN_ID       VARCHAR(100) NOT NULL,
    RANK_STR        VARCHAR(100) NOT NULL, -- Lexorank 정렬 문자열
    -- BaseModel
    SRV_ID          VARCHAR(50)  NOT NULL DEFAULT 'CIRA',
    TENANT          VARCHAR(50)  NOT NULL DEFAULT 'TAS',
    TRACE_ID        VARCHAR(100) NOT NULL,
    USE_STAT_CD     VARCHAR(40)  NOT NULL DEFAULT 'Usable',
    EVNT_NM         VARCHAR(100) NOT NULL,
    PREV_EVNT_NM     VARCHAR(100),
    ACT_CD       VARCHAR(100),
    ACT_CM          TEXT,
    CREATED_BY      VARCHAR(40),
    CREATED_AT      TIMESTAMP    NOT NULL DEFAULT NOW(),
    MODIFIED_BY     VARCHAR(40),
    MODIFIED_AT     TIMESTAMP    NOT NULL DEFAULT NOW(),

    CONSTRAINT PK_SN_CIRA_ISSUE_POSITION PRIMARY KEY (OBJ_ID),
    CONSTRAINT UK_SN_CIRA_ISSUE_POSITION UNIQUE (ISSUE_ID, COLUMN_ID),
    CONSTRAINT FK_SN_CIRA_ISSUE_POSITION_ISSUE FOREIGN KEY (ISSUE_ID) REFERENCES SN_CIRA_ISSUE (OBJ_ID),
    CONSTRAINT FK_SN_CIRA_ISSUE_POSITION_COLUMN FOREIGN KEY (COLUMN_ID) REFERENCES SN_CIRA_BOARD_COLUMN (OBJ_ID)
);


CREATE INDEX IDX_SN_CIRA_ISSUE_POSITION_COLUMN_ID ON SN_CIRA_ISSUE_POSITION (COLUMN_ID);
CREATE INDEX IDX_SN_CIRA_ISSUE_POSITION_RANK ON SN_CIRA_ISSUE_POSITION (COLUMN_ID, RANK_STR);

COMMENT ON TABLE SN_CIRA_ISSUE_POSITION IS '보드 내 이슈 위치 (Lexorank)';
COMMENT ON COLUMN SN_CIRA_ISSUE_POSITION.ISSUE_ID IS '이슈 ID (FK → SN_CIRA_ISSUE)';
COMMENT ON COLUMN SN_CIRA_ISSUE_POSITION.COLUMN_ID IS '보드 컬럼 ID (FK → SN_CIRA_BOARD_COLUMN)';
COMMENT ON COLUMN SN_CIRA_ISSUE_POSITION.RANK_STR IS 'Lexorank 정렬 문자열';
COMMENT ON COLUMN SN_CIRA_ISSUE_POSITION.OBJ_ID IS '오브젝트 ID (PK, UUID)';
COMMENT ON COLUMN SN_CIRA_ISSUE_POSITION.SRV_ID IS '서비스명';
COMMENT ON COLUMN SN_CIRA_ISSUE_POSITION.TENANT IS '테넌트';
COMMENT ON COLUMN SN_CIRA_ISSUE_POSITION.TRACE_ID IS '트레이스 ID';
COMMENT ON COLUMN SN_CIRA_ISSUE_POSITION.USE_STAT_CD IS '사용 상태';
